const DEFAULT_LANG = 'fr'

/**
 * Traduit une chaîne d'émotion (ex: "Joy (85%)") dans la langue cible.
 * Conserve le pourcentage s'il est présent.
 */
export function translateEmotion(emotionString, lang = DEFAULT_LANG) {
  if (!emotionString || typeof emotionString !== 'string') return emotionString

  const match = emotionString.match(/^(.+?)( \(\d+%\))?$/)
  if (!match) return emotionString

  const englishName = match[1].trim()
  const percentage = match[2] || ''

  const dict = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG]
  const translated = dict[englishName]

  return translated ? translated + percentage : emotionString
}
